#!/usr/bin/env python3
"""Generate the OMS review copy from the canonical manuscript, without textual drift."""
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[2]
PAPER = ROOT / "paper"
OUT = PAPER / "oms"


def main():
    source = (PAPER / "main.tex").read_text()
    preamble, document = source.split(r"\begin{document}", 1)
    preamble = preamble.replace(r"\documentclass[11pt]{article}", r"\documentclass{interact}")
    preamble = preamble.replace(r"\usepackage[margin=1in]{geometry}" + "\n", "")
    # Interact reserves \doi for article metadata; here it links archive identifiers.
    preamble = preamble.replace(r"\newcommand{\doi}", r"\renewcommand{\doi}")
    author_start = preamble.index(r"\author{")
    preamble = preamble[:author_start] + r"""\author{
\name{Mathias Rodr\'iguez Castro\thanks{CONTACT Mathias Rodr\'iguez Castro.
Email: mathiasr@fing.edu.uy. ORCID: 0009-0002-7235-7677.}}
\affil{Facultad de Ingenier\'ia, Universidad de la Rep\'ublica, Montevideo, Uruguay}}
\usepackage{etoolbox}
\makeatletter
\patchcmd{\@maketitle}
  {\ifsuppldata\else}
  {\iftrue\else}
  {}{\PackageError{oms}{Could not suppress placeholder article history}{}}
\makeatother
\emergencystretch=1.5em
\raggedbottom
\setcounter{secnumdepth}{3}
\setlength{\skip\footins}{6pt plus 2pt minus 2pt}
"""
    document = document.replace(r"\bibliographystyle{plainnat}", r"\bibliographystyle{tfq}")
    # Interact supplies its own punctuation for run-in paragraph headings.
    document = re.sub(r"\\paragraph\{([^{}]*?)\.\}", r"\\paragraph{\1}", document)
    document = document.replace(r"\noindent\textbf{Keywords:}", r"\begin{keywords}", 1)
    document = document.replace("finite-precision arithmetic.\n\n\\medskip",
                                "finite-precision arithmetic.\n\\end{keywords}\n\n\\medskip", 1)
    # Keep the publisher's text dimensions; fit only naturally wide tabular inputs.
    for table in ("fixed-basis", "budget-paired", "instance-bank"):
        token = r"\input{tables/" + table + "}"
        assert document.count(token) == 1, table
        document = document.replace(token, r"\resizebox{\linewidth}{!}{" + token + "}")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "main_oms.tex").write_text(
        "% Optimization Methods and Software review copy; generated by build_oms.py.\n"
        + preamble + r"\begin{document}" + document)
    abstract = document.split(r"\begin{abstract}", 1)[1].split(r"\end{abstract}", 1)[0].strip()
    (OUT / "abstract.txt").write_text(abstract + "\n")
    # Recursively mirror all manuscript inputs; the source ZIP compiles independently.
    pending = re.findall(r"\\input\{([^}]+)\}", document)
    wanted = {"research-references.bib"}
    figures = set(re.findall(r"\\includegraphics(?:\[[^]]*\])?\{([^}]+)\}", document))
    while pending:
        name = pending.pop() + ".tex"
        if name in wanted:
            continue
        wanted.add(name)
        text = (PAPER / name).read_text()
        pending += re.findall(r"\\input\{([^}]+)\}", text)
        figures.update(re.findall(r"\\includegraphics(?:\[[^]]*\])?\{([^}]+)\}", text))
    for name in sorted(wanted):
        destination = OUT / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not destination.exists() or destination.read_bytes() != (PAPER / name).read_bytes():
            shutil.copy2(PAPER / name, destination)
    for figure in sorted(figures):
        origin = next(PAPER / folder / figure for folder in ("figs/research", "figs")
                      if (PAPER / folder / figure).exists())
        destination = OUT / "figs/research" / figure
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not destination.exists() or destination.read_bytes() != origin.read_bytes():
            shutil.copy2(origin, destination)
    print(f"Generated paper/oms/main_oms.tex; abstract: {len(abstract.split())} words")


if __name__ == "__main__":
    main()
