#!/usr/bin/env python3
"""Render the selected ORF follow-up tables from the frozen, replayable results."""
import json
from orf_config import ORF, VERIFIED


def table(caption, label, columns, header, rows, note='', wide=False):
    body = '\\begin{tabular}{'+columns+'}\n\\toprule\n'+header+r' \\'+'\n\\midrule\n'
    body += '\n'.join(' & '.join(map(str, r))+r' \\' for r in rows)
    body += '\n\\bottomrule\n\\end{tabular}\n'
    if wide:
        body = '\\resizebox{\\linewidth}{!}{%\n'+body+'}\n'
    return ('% Generated by scripts/research/orf_followup_tables.py\n'
            '\\begin{table}[htbp]\n\\centering\n\\small\n'
            '\\caption{'+caption+'}\n\\label{'+label+'}\n'+body+
            ('\\par\\smallskip\n\\begin{minipage}{\\linewidth}\\footnotesize\n'+note+
             '\n\\end{minipage}\n' if note else '')+'\\end{table}\n')


def ratio(item, metric='offline_verified_available'):
    d=item[metric]
    return f"{d['PAR2_paired_geometric_ratio']:.3f} [{d['lower95']:.3f}, {d['upper95']:.3f}]"


def render():
    d=json.loads((VERIFIED/'COMPUTATIONAL_RESULTS.json').read_text())
    p=json.loads((VERIFIED/'PRECISION_RESULTS.json').read_text())
    first=d['experiment_I']
    policies={r['policy']:r for r in first['policy_results']}
    order=['Base','L2','Budget-L2','L2-NF3']
    primary=next(c for c in first['comparisons'] if c['control']=='L2' and c['tau']==.001)
    n=primary['common_success_pairs']
    common=primary['offline_verified_available']['common_success_geometric_ratio']
    assert n==44 and all(r['runs']==72 for r in policies.values())
    rows=[]
    for name in order:
        r=policies[name]
        rows.append([name,f"{r['targets']['0.001']}/72",f"{r['targets']['0.01']}/72",
                     f"{r['final_physical_pass']}/72",r['detected_bound_contradictions']])
    out={}
    out['verified-summary-table.tex']=table(
        'Verified-candidate targets on 24 known scenarios and three new seeds per policy.',
        'tab:orf-verified-candidates','lrrrr',
        r'Policy & Target 0.1\% & Target 1\% & Final budgets & Bound flags',rows,
        'Budget-L2/L2 verified-availability PAR2: '+ratio(primary)+
        f' (95\\% scenario-cluster interval); common-success availability ratio: {common:.3f}'
        f' ({n} pairs). Flags count independently contradicted bounds; absence of a flag'
        ' does not certify optimality.')
    out['verified-target-table.tex']=table(
        'Candidate-study final checks and target attainment; all 72 assignments per policy are retained.',
        'tab:orf-verified-targets','lrrrrrr',
        r'Policy & Target 0.1\% & Target 1\% & Physical & Domains & Other rows & Bound flags',
        [[name,policies[name]['targets']['0.001'],policies[name]['targets']['0.01'],
          policies[name]['final_physical_pass'],policies[name]['final_domain_pass'],
          policies[name]['final_other_rows_pass'],policies[name]['detected_bound_contradictions']]
         for name in order],wide=True)
    out['verified-comparison-table.tex']=table(
        'Budget-L2 relative to each control: paired geometric penalized scores and common-success times.',
        'tab:orf-verified-par2','llrllr',
        r'Control & Target & Common pairs & Discovery PAR2 [95\%] & Availability PAR2 [95\%] & Common availability',
        [[r['control'],r'0.1\%' if r['tau']==.001 else r'1\%',r['common_success_pairs'],
          ratio(r,'process_discovery'),ratio(r),
          f"{r['offline_verified_available']['common_success_geometric_ratio']:.3f}"]
         for r in first['comparisons']],wide=True)
    lookup={(r['contract'],r['policy']):r for r in p['observed_final_precision']}
    rows=[]
    for contract,label in [('b10',r'10\,m$^3$'),('b100',r'100\,m$^3$'),
                           ('b1000',r'1,000\,m$^3$'),('heterogeneous','Heterogeneous')]:
        cells=[lookup[contract,policy] for policy in ['L2','Budget-L2','Export-Budget-L2']]
        assert all(c['final_physical_budget_pass']==18 and c['violating_rows']==0 for c in cells)
        rows.append([label,'18/18',*[f"{c['max_q']:.3g}" for c in cells]])
    out['verified-precision-table.tex']=table(
        'Observed physical margins under four specifications; each policy passes all 18 final points per specification.',
        'tab:orf-verified-precision','llrrr',
        r'Specification & Each policy passes & Max $q$, L2 & Max $q$, Budget-L2 & Max $q$, Export-Budget-L2',
        rows,wide=True)
    rows=[]
    scopes=[('CPLEX',d['CPLEX'])]+[(r'Gurobi SF='+k,d['Gurobi_internal_scaling'][k]) for k in ['-1','0','2']]
    for label,scope in scopes:
        pr={r['policy']:r for r in scope['policy_results']}
        b,l=pr['Budget-L2'],pr['L2']
        r=next(c for c in scope['comparisons'] if c['control']=='L2' and c['tau']==.001)
        runs=b['runs']
        rows.append([label,str(scope['scenarios']),
                     f"{b['targets']['0.001']}/{runs}; {l['targets']['0.001']}/{runs}",
                     ratio(r),f"{b['detected_bound_contradictions']}; {l['detected_bound_contradictions']}"])
    out['verified-robustness-table.tex']=table(
        'Robustness subsets at the primary target; paired entries are Budget-L2 then L2. SF denotes ScaleFlag.',
        'tab:orf-verified-robustness','lrlll',
        r'Configuration & Scenarios & Target hits, Budget; L2 & Availability PAR2 [95\%] & Bound flags',rows,
        'All policies satisfy final physical budgets. Exact-bound rejections affect CPLEX target counts;'
        ' the post hoc projection sensitivity is reported in the text. Work units are not compared across solvers.',wide=True)
    return out


def main():
    for name,content in render().items():
        (ORF/'editorial'/name).write_text(content)
    print('Rendered five ORF follow-up tables from frozen results.')


if __name__=='__main__':
    main()
